#!/usr/bin/python3
"""Turn a binary file into a Calypsi assembler source that defines it as a
public byte array.

Hexwar links its tile sheet in rather than reading it off a disk. res/tiles.fci
is 6573 bytes, and carrying it in the program buys away a whole class of
problems the two earlier MEGA65 projects in this tree had to work around:

- no stdio in the binary, which in ~/commodore/mega65/hexgame was worth about
  2.7 KB once the last fopen went;
- no PETSCII file name trap. A CBM directory holds PETSCII, and Calypsi (unlike
  cc65) compiles string literals as written, so a lower case name in a fopen
  matches nothing and yields an *empty file* rather than an error;
- no ordering rule. Reading a file needs a KERNAL, so anything that disturbs
  the memory map has to happen afterwards. Hexwar does not disturb it either,
  but this removes the question.

Usage: bin2s.py <infile> <outfile> <symbol>
"""

import sys


def main():
    if len(sys.argv) != 4:
        sys.exit("usage: %s <infile> <outfile> <symbol>" % sys.argv[0])
    infile, outfile, symbol = sys.argv[1:]

    with open(infile, "rb") as f:
        data = f.read()

    with open(outfile, "w") as out:
        out.write("; Generated by tools/bin2s.py from %s -- do not edit.\n" %
                  infile)
        out.write("; %d bytes.\n\n" % len(data))
        # **`code`, not `data`.** Calypsi's `data` is *initialised* data: the
        # linker keeps an image of it and the startup copies that image into
        # RAM before main(), so a 6.5 KB blob would cost 13 KB of the 32 and be
        # copied for nothing. A `code` section is loaded straight from the PRG
        # and left alone, which is what a read-only asset wants.
        out.write("            .section code\n")
        out.write("            .public %s\n" % symbol)
        out.write("            .public %s_size\n\n" % symbol)
        out.write("%s_size:   .word %d\n" % (symbol, len(data)))
        out.write("%s:\n" % symbol)
        for i in range(0, len(data), 16):
            row = data[i:i + 16]
            out.write("            .byte " +
                      ", ".join("0x%02x" % b for b in row) + "\n")
        out.write("\n            .end\n")


if __name__ == "__main__":
    main()
