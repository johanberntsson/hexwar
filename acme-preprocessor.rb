#!/bin/ruby
#
# This preprocessor provides some higher-level structures to
# 6502 assembler, using the acme cross-compiler
#
# 1. function statement
# function are now defined as
#     function {
#         ...
#     }
#
# 2. if statement
# if statements are supported
#     if zero {
#         ...
#     }
# else is also supported
#     if zero {
#         ...
#     } else {
#         ...
#     }
#
#

require 'optparse'

if ARGV.length != 2 then
    puts "Usage: #{$0} <source file> <acme file>"
    exit 0
end

input = IO.readlines(ARGV[0])

Function_None = 1
Function_Defined = 2
Function_StartFound = 3
function_status = Function_None

If_None = 1
If_Defined = 2
if_status = If_None
if_cnt = 0

output = []
#output.append "; Generated by #{$0}. Do not edit by hand"
#output.append ";"
input.each do |line|
    # If
    if if_status == If_None then
        args = line.scan(/(if)\s*(\w*)\s*{/i)
        if args.length > 0 then
          if_status = If_Defined
          line = "    bne .if_label#{if_cnt}"
        end
    elsif line.match(/}\s*else\s*{/i) then
        line = "    jmp .if_label#{if_cnt + 1}\n.if_label#{if_cnt}"
        if_cnt = if_cnt + 1
    end

    # function
    if function_status == Function_None then
        args = line.scan(/^(function)\s*(\w*)\s*({)?/i)
        if args.length > 0 then
            if_cnt = 0
            if args[0][2].nil? then
                function_status = Function_Defined
            else
                function_status = Function_StartFound
            end
            line = args[0][1]
        end
    elsif line.match("^\s*{\s*$") and function_status == Function_Defined then
            # single {, skip (function statement)
            line = nil
            function_status = Function_StartFound
    end

    # end of block, could be function or if statement
    if line.match("^\s*}\s*$") then
        if if_status != If_None then
            # This is the end of an if statement
            line = ".if_label#{if_cnt}";
            if_cnt = if_cnt + 1
            if_status = If_None
        elsif function_status == Function_StartFound then
            # This is the end of an function statement
            line = nil
            function_status = Function_None
        end
    end


    output.append(line) if !line.nil?
end

File.open(ARGV[1], "w+") do |f|
    output.each do |element|
        f.puts element
    end
end
